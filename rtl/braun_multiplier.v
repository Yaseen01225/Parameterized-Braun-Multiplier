 `timescale 1ns / 1ps  // Set simulation time unit to 1 ns and precision to 1 ps.


 // ============================================================================
 // Module 1: Partial Product Generator
 // ============================================================================
 // This module generates one partial-product row.
 // If b = 1, the output equals a.
 // If b = 0, the output is zero.

 module partial_product (
     input  wire [3:0] a,  // 4-bit multiplicand.
     input  wire       b,  // One bit of the multiplier.
     output wire [3:0] pp  // Generated 4-bit partial product.
 );

     // Replicate b four times and AND it with every bit of a.
     // Example: a = 1010, b = 1 gives pp = 1010.
     // Example: a = 1010, b = 0 gives pp = 0000.
     assign pp = a & {4{b}};

 endmodule  // End of the partial-product generator.


 // ============================================================================
 // Module 2: 4-Bit Unsigned Multiplier
 // ============================================================================
 // Generate four partial products, shift them to their correct bit positions,
 // and add the aligned rows to obtain the final product.

 module braun_multiplier (
     input  wire [3:0] a,       // First unsigned operand: 0 to 15.
     input  wire [3:0] b,       // Second unsigned operand: 0 to 15.
     output wire [7:0] product  // Full product: 0 to 225.
 );

     // Wires that carry the partial products generated by each multiplier bit.
     wire [3:0] pp0;  // Partial product controlled by b[0].
     wire [3:0] pp1;  // Partial product controlled by b[1].
     wire [3:0] pp2;  // Partial product controlled by b[2].
     wire [3:0] pp3;  // Partial product controlled by b[3].

     // Each row is extended to 8 bits and shifted to the correct weight.
     wire [7:0] row0;  // Row shifted left by 0 positions.
     wire [7:0] row1;  // Row shifted left by 1 position.
     wire [7:0] row2;  // Row shifted left by 2 positions.
     wire [7:0] row3;  // Row shifted left by 3 positions.

     // Instantiate four partial-product generators.
     // Each instance processes one bit of multiplier b.
     partial_product u_pp0 (
         .a(a),       // Connect the multiplicand.
         .b(b[0]),    // Use the least-significant multiplier bit.
         .pp(pp0)     // Store the generated partial product.
     );

     partial_product u_pp1 (
         .a(a),       // Connect the multiplicand.
         .b(b[1]),    // Use multiplier bit 1.
         .pp(pp1)     // Store the generated partial product.
     );

     partial_product u_pp2 (
         .a(a),       // Connect the multiplicand.
         .b(b[2]),    // Use multiplier bit 2.
         .pp(pp2)     // Store the generated partial product.
     );

     partial_product u_pp3 (
         .a(a),       // Connect the multiplicand.
         .b(b[3]),    // Use the most-significant multiplier bit.
         .pp(pp3)     // Store the generated partial product.
     );

     // Align each partial product according to its multiplier-bit position.
     // Concatenation adds leading zeros and trailing zeros as required.

     assign row0 = {4'b0000, pp0};
     // No shift is needed because b[0] has weight 2^0.

     assign row1 = {3'b000, pp1, 1'b0};
     // Append one zero to shift pp1 left by one bit (multiply by 2).

     assign row2 = {2'b00, pp2, 2'b00};
     // Append two zeros to shift pp2 left by two bits (multiply by 4).

     assign row3 = {1'b0, pp3, 3'b000};
     // Append three zeros to shift pp3 left by three bits (multiply by 8).

     // Add all four aligned rows to produce the complete multiplication result.
     assign product = row0 + row1 + row2 + row3;

 endmodule  // End of the multiplier module.
